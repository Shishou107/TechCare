CREATE UNIQUE INDEX UX_RefreshTokens_Hash ON Security.RefreshTokens(TokenHash);
CREATE INDEX IX_RefreshTokens_Session ON Security.RefreshTokens(SessionId,ExpiresAtUtc);
CREATE INDEX IX_RefreshTokens_User_Expiry ON Security.RefreshTokens(UserId,ExpiresAtUtc);

