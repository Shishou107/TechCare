-- SECURITY / RBAC
CREATE TABLE Security.Users(
 UserId bigint IDENTITY PRIMARY KEY, BranchId int NULL,
 UserName nvarchar(100) NOT NULL, NormalizedUserName nvarchar(100) NOT NULL,
 Email nvarchar(254), NormalizedEmail nvarchar(254), PhoneNumber nvarchar(30),
